import pandas as pd
df = pd.read_csv("scores_2026.csv", dtype={"학번": "string"})


def 정제(df):
    # 원본 데이터를 보존하기 위해 복사본을 만든다.
    df_정제 = df.copy()

    # 점수가 비어 있는 행을 삭제한다.
    df_정제 = df_정제.dropna(subset=["점수"])
    print(f"점수가 비어 있는 행 삭제 후 남은 행 수: {len(df_정제)}")

    # 모든 열의 값이 같은 중복 행을 삭제한다.
    df_정제 = df_정제.drop_duplicates()
    print(f"중복 행 삭제 후 남은 행 수: {len(df_정제)}")

    # 반과 과목 값 앞뒤의 공백을 제거한다.
    df_정제["반"] = df_정제["반"].str.strip()
    df_정제["과목"] = df_정제["과목"].str.strip()
    print(f"공백 제거 후 남은 행 수: {len(df_정제)}")

    # 점수가 0점 미만이거나 100점을 초과하는 행을 삭제한다.
    df_정제 = df_정제[df_정제["점수"].between(0, 100)]
    print(f"점수 범위 정리 후 남은 행 수: {len(df_정제)}")

    return df_정제


df_정제 = 정제(df)

